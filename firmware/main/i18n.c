_Static_assert(sizeof(MSG) / sizeof(MSG[0]) == LANG_COUNT, "MSG row count != LANG_COUNT");
_Static_assert(sizeof(MSG[0]) / sizeof(MSG[0][0]) == STR_COUNT, "MSG col count != STR_COUNT");

static _Atomic i18n_lang_t s_lang = LANG_EN;  /* default until app_config seeds ui_lang */

void i18n_set_lang(i18n_lang_t lang) {
    if (lang >= 0 && lang < LANG_COUNT) atomic_store(&s_lang, lang);
}
i18n_lang_t i18n_get_lang(void) { return atomic_load(&s_lang); }

const char *tr_l(i18n_lang_t lang, i18n_str_t id) {
    if (id < 0 || id >= STR_COUNT) return "";
    if (lang < 0 || lang >= LANG_COUNT) lang = LANG_EN;
    const char *s = MSG[lang][id];
    if (!s) s = MSG[LANG_EN][id]; /* untranslated cell → English */
    return s ? s : "";
}
const char *tr(i18n_str_t id) { return tr_l(atomic_load(&s_lang), id); }

void i18n_init(void) {
    /* Dev safety net: a forgotten cell falls back to English at runtime; log it
     * once at boot so it's caught (mirrors app_config's NVS-key boot guard). */
    int missing = 0;
    for (int l = 0; l < LANG_COUNT; l++)
        for (int i = 0; i < STR_COUNT; i++)
            if (!MSG[l][i]) {
                ESP_LOGE(TAG, "missing translation: lang=%d id=%d", l, i);
                missing++;
            }
    if (missing) ESP_LOGE(TAG, "%d untranslated string(s) — falling back to EN", missing);
}
